/* 8x16 font. Design rules:
 *  - 7px wide, bit 0 left empty as letter spacing, 2px strokes
 *  - everything shares one baseline: bottom row (row 15)
 *  - caps/digits: 14 rows (rows 2-15); lowercase x-height: 9 rows (rows 7-15)
 *  - ascenders (b d f h k l) reach row 2; g j p q y keep their tail inside the cell
 *    instead of dropping below the baseline (nothing is left under row 15) */

